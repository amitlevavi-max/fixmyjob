-- ── Pay with vs without a certification, for one SOC occupation ─────────────
-- Most specific Census occupation first (exact SOC, then broad group).
create or replace function public.cert_pay_gap(p_soc text)
returns table (
  census_code text, census_title text, n_cert integer, n_none integer,
  weekly_cert numeric, weekly_none numeric, gap_low numeric, gap_high numeric,
  reliable boolean, period_from text, period_to text
)
language sql stable
set search_path = public
as $$
  select c.census_code, c.title, g.n_cert, g.n_none, g.weekly_cert, g.weekly_none,
         g.gap_low, g.gap_high, g.reliable, g.period_from, g.period_to
  from census_occupations c
  join cert_pay_gaps g on g.census_code = c.census_code
  where c.soc = p_soc or p_soc like c.soc_like
  order by (c.soc = p_soc) desc, length(replace(c.soc_like, '_', '')) desc
  limit 1;
$$;
grant execute on function public.cert_pay_gap(text) to anon, authenticated;

-- ── Approved training programs for one occupation ───────────────────────────
-- Programs in the user's state first (all states when p_state is null);
-- those with published results first, then higher completion, then cheaper.
create or replace function public.training_options(p_soc text, p_state text default null, p_limit int default 10)
returns jsonb
language sql stable
set search_path = public
as $$
  with matches as (
    select * from training_programs where p_soc = any(socs)
  ), local as (
    select * from matches where p_state is null or state = p_state
  )
  select jsonb_build_object(
    'summary', jsonb_build_object(
      'in_state',          (select count(*) from local),
      'nationwide',        (select count(*) from matches),
      'median_weeks',      (select percentile_cont(0.5) within group (order by weeks) from local where weeks > 0),
      'median_tuition',    (select percentile_cont(0.5) within group (order by tuition) from local where tuition > 0),
      'median_completion', (select percentile_cont(0.5) within group (order by completion_rate) from local where completion_rate is not null),
      'with_results',      (select count(*) from local where median_q2_earnings is not null),
      'reported_to',       (select max(reported_at) from local)
    ),
    'programs', coalesce((
      select jsonb_agg(to_jsonb(p) - 'imported_at' - 'provider_id' - 'reporting_state')
      from (
        select * from local
        order by (median_q2_earnings is not null) desc,
                 (completion_rate is not null and coalesce(exited, 0) >= 10) desc,
                 completion_rate desc nulls last,
                 tuition asc nulls last
        limit greatest(1, least(p_limit, 50))
      ) p
    ), '[]'::jsonb)
  );
$$;
grant execute on function public.training_options(text, text, int) to anon, authenticated;
