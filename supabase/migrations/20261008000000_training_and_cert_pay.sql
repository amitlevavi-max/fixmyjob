-- ─────────────────────────────────────────────────────────────────────────────
-- Training programs and the pay difference for certified workers.
--
-- 1. training_programs — every WIOA-approved training program with its
--    published results, from the U.S. Dept. of Labor ETA-9171 report
--    (TrainingProviderResults.gov). Loaded by scripts/import-training-programs.mjs
--    from the DOL file; values DOL suppressed (-1) are stored as null.
--
-- 2. census_occupations — Census 2018 occupation codes (used by the Current
--    Population Survey) and the SOC codes they cover (Census Bureau crosswalk,
--    "2018 Census Occupation Code List", Sept 2019).
--
-- 3. cert_pay_gaps — per Census occupation: median weekly pay of full-time
--    employees WITH an active professional certification or license vs WITHOUT,
--    from 24 months of CPS microdata (Census Data API). Filled by the
--    refresh-cert-pay Edge Function.
-- ─────────────────────────────────────────────────────────────────────────────

create table if not exists public.training_programs (
  id                  text primary key,         -- hash of provider + program + state
  provider_id         text,
  provider            text not null,
  name                text not null,
  credential          text,
  cip                 text,
  cip_title           text,
  socs                text[] not null,          -- '53-3032' (up to 3, from the DOL record)
  state               text,                     -- where the program is
  reporting_state     text,                     -- state that approved it
  city                text,
  zip                 text,
  lat                 double precision,
  lon                 double precision,
  format              text,                     -- in_person | online | hybrid | mixed
  url                 text,
  tuition             numeric,                  -- out of pocket, non-WIOA
  supplies            numeric,
  weeks               numeric,                  -- full-time length
  prerequisites       text,                     -- ETA-9171 DE115 code
  exited              numeric,                  -- people who left the program (outcome base)
  completion_rate     numeric,                  -- 0..1
  employed_q2_rate    numeric,                  -- employed 2nd quarter after exit, 0..1
  employed_q4_rate    numeric,
  median_q2_earnings  numeric,                  -- QUARTERLY median earnings, 2nd quarter after exit
  credential_rate     numeric,
  reported_at         date,
  imported_at         timestamptz not null default now()
);
create index if not exists training_programs_socs_idx on public.training_programs using gin (socs);
create index if not exists training_programs_state_idx on public.training_programs (state);
alter table public.training_programs enable row level security;
drop policy if exists "read training_programs" on public.training_programs;
create policy "read training_programs" on public.training_programs for select using (true);

create table if not exists public.census_occupations (
  census_code  text primary key,               -- '9130'
  title        text not null,
  soc          text not null,                  -- as published: '53-3030', '13-20XX'
  soc_like     text                            -- LIKE pattern: '53-303_'
);
alter table public.census_occupations enable row level security;
drop policy if exists "read census_occupations" on public.census_occupations;
create policy "read census_occupations" on public.census_occupations for select using (true);

